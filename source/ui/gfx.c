/*
 * Mode 3 is a packed 16-bit framebuffer.  GBA builds route contiguous spans
 * through a small ARM/IWRAM routine that aligns the destination and emits
 * word stores.  Host builds keep this exact C fallback so clipping and stride
 * behavior remain covered by the normal gfx tests.
 */
#if defined(GCALC_GBA_ARM_FAST)
extern void gcalcArmFill16(volatile u16 *destination, u16 value, u32 count);
#else
static void gcalcArmFill16(volatile u16 *destination, u16 value, u32 count)
{
    while (count-- != 0)
        *destination++ = value;
}
#endif

