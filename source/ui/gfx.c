/*
 * The established UI font uses a 5x9 cell with deliberately doubled cap and
 * baseline strokes.  Selecting these seven scanlines removes only those
 * doubled strokes and yields a complete 5x7 printable-ASCII face without a
 * second 665-byte glyph table.  The mapping is fixed, so every public 5x7
 * glyph has exactly seven addressable bitmap rows.
 */
static const u8 gfxFont5x7Rows[GFX_ASCII5X7_HEIGHT] = {
    0, 2, 3, 4, 5, 6, 8
};

enum GfxClipCode {
    GFX_CLIP_LEFT = 1,
    GFX_CLIP_RIGHT = 2,
    GFX_CLIP_TOP = 4,
    GFX_CLIP_BOTTOM = 8
};

static u8 gfxSurfaceValid(const GfxSurface *surface)
{
    return surface != NULL && surface->pixels != NULL &&
           surface->width > 0 && surface->height > 0 &&
           surface->stride >= surface->width;
}

static u8 gfxClipCode(const GfxSurface *surface, s32 x, s32 y)
{
    u8 code = 0;

    if (x < 0)
        code |= GFX_CLIP_LEFT;
    else if (x >= surface->width)
        code |= GFX_CLIP_RIGHT;

    if (y < 0)
        code |= GFX_CLIP_TOP;
    else if (y >= surface->height)
        code |= GFX_CLIP_BOTTOM;

    return code;
}

static u8 gfxClipLine(const GfxSurface *surface,
                      s32 *x0, s32 *y0, s32 *x1, s32 *y1)
{
    u8 code0;
    u8 code1;

    for (;;) {
        s32 x;
        s32 y;
        u8 outside;

        code0 = gfxClipCode(surface, *x0, *y0);
        code1 = gfxClipCode(surface, *x1, *y1);

        if ((code0 | code1) == 0)
            return 1;
        if ((code0 & code1) != 0)
            return 0;

        outside = code0 != 0 ? code0 : code1;
        x = code0 != 0 ? *x0 : *x1;
        y = code0 != 0 ? *y0 : *y1;

        if ((outside & GFX_CLIP_TOP) != 0) {
            if (*y1 == *y0)
                return 0;
            x = *x0 + (s32)(((s64)(*x1 - *x0) * (-*y0)) /
                            (*y1 - *y0));
            y = 0;
        } else if ((outside & GFX_CLIP_BOTTOM) != 0) {
            s32 edge = (s32)surface->height - 1;
            if (*y1 == *y0)
                return 0;
            x = *x0 + (s32)(((s64)(*x1 - *x0) * (edge - *y0)) /
                            (*y1 - *y0));
            y = edge;
        } else if ((outside & GFX_CLIP_RIGHT) != 0) {
            s32 edge = (s32)surface->width - 1;
            if (*x1 == *x0)
                return 0;
            y = *y0 + (s32)(((s64)(*y1 - *y0) * (edge - *x0)) /
                            (*x1 - *x0));
            x = edge;
        } else {
            if (*x1 == *x0)
                return 0;
            y = *y0 + (s32)(((s64)(*y1 - *y0) * (-*x0)) /
                            (*x1 - *x0));
            x = 0;
        }

        if (code0 != 0) {
            *x0 = x;
            *y0 = y;
        } else {
            *x1 = x;
            *y1 = y;
        }
    }
}

static void gfxLineS32(GfxSurface *surface,
                       s32 x0, s32 y0, s32 x1, s32 y1, u16 color)
{
    s32 deltaX;
    s32 deltaY;
    s32 stepX;
    s32 stepY;
    s32 error;

    if (!gfxSurfaceValid(surface) ||
        !gfxClipLine(surface, &x0, &y0, &x1, &y1))
        return;

    deltaX = x1 >= x0 ? x1 - x0 : x0 - x1;
    deltaY = y1 >= y0 ? y1 - y0 : y0 - y1;
    stepX = x0 < x1 ? 1 : -1;
    stepY = y0 < y1 ? 1 : -1;
    error = deltaX - deltaY;

    for (;;) {
        s32 doubledError;

        surface->pixels[y0 * surface->stride + x0] = color;
        if (x0 == x1 && y0 == y1)
            break;

        doubledError = error * 2;
        if (doubledError > -deltaY) {
            error -= deltaY;
            x0 += stepX;
        }
        if (doubledError < deltaX) {
            error += deltaX;
            y0 += stepY;
        }
    }
}

void gfxClear(GfxSurface *surface, u16 color)
{
    s32 y;

    if (!gfxSurfaceValid(surface))
        return;

    if (surface->stride == surface->width) {
        gcalcArmFill16(surface->pixels, color,
                       (u32)surface->width * (u32)surface->height);
        return;
    }

    for (y = 0; y < surface->height; ++y) {
        volatile u16 *row = surface->pixels + y * surface->stride;
        gcalcArmFill16(row, color, (u32)surface->width);
    }
}

void gfxPixel(GfxSurface *surface, s16 x, s16 y, u16 color)
{
    if (!gfxSurfaceValid(surface) || x < 0 || y < 0 ||
        x >= surface->width || y >= surface->height)
        return;

    surface->pixels[(s32)y * surface->stride + x] = color;
}

void gfxFillRect(GfxSurface *surface, s16 x, s16 y, s16 width, s16 height,
                 u16 color)
{
    s32 left;
    s32 top;
    s32 right;
    s32 bottom;
    s32 rowIndex;

    if (!gfxSurfaceValid(surface) || width <= 0 || height <= 0)
        return;

    left = x;
    top = y;
    right = left + width;
    bottom = top + height;

    if (left < 0)
        left = 0;
    if (top < 0)
        top = 0;
    if (right > surface->width)
        right = surface->width;
    if (bottom > surface->height)
        bottom = surface->height;
    if (left >= right || top >= bottom)
        return;

    for (rowIndex = top; rowIndex < bottom; ++rowIndex) {
        volatile u16 *row = surface->pixels +
                            rowIndex * surface->stride + left;
        gcalcArmFill16(row, color, (u32)(right - left));
    }
}

void gfxRect(GfxSurface *surface, s16 x, s16 y, s16 width, s16 height,
             u16 color)
{
    s32 right;
    s32 bottom;

    if (!gfxSurfaceValid(surface) || width <= 0 || height <= 0)
        return;

    right = (s32)x + width - 1;
    bottom = (s32)y + height - 1;
    gfxLineS32(surface, x, y, right, y, color);
    if (height > 1)
        gfxLineS32(surface, x, bottom, right, bottom, color);
    gfxLineS32(surface, x, y, x, bottom, color);
    if (width > 1)
        gfxLineS32(surface, right, y, right, bottom, color);
}

void gfxLine(GfxSurface *surface, s16 x0, s16 y0, s16 x1, s16 y1,
             u16 color)
{
    gfxLineS32(surface, x0, y0, x1, y1, color);
}

void gfxChar(GfxSurface *surface, s16 x, s16 y, char character, u16 color)
{
    u8 code = (u8)character;
    u8 row;

    if (!gfxSurfaceValid(surface))
        return;
    if (code < 0x20 || code > 0x7e)
        code = (u8)'?';

    for (row = 0; row < GFX_FONT_HEIGHT; ++row) {
        u8 column;
        u8 bits = gfxFont[code - 0x20][row];
        s32 targetY = (s32)y + row;

        if (targetY < 0 || targetY >= surface->height)
            continue;
        for (column = 0; column < GFX_FONT_WIDTH; ++column) {
            s32 targetX = (s32)x + column;
            if (targetX >= 0 && targetX < surface->width &&
                (bits & (1u << (GFX_FONT_WIDTH - 1 - column))) != 0) {
                surface->pixels[targetY * surface->stride + targetX] = color;
            }
        }
    }
}

void gfxText(GfxSurface *surface, s16 x, s16 y, const char *text, u16 color)
{
    s32 originX = x;
    s32 penX = x;
    s32 penY = y;

    if (!gfxSurfaceValid(surface) || text == NULL)
        return;

    while (*text != '\0') {
        unsigned char character = (unsigned char)*text++;

        if (character == '\n') {
            penX = originX;
            penY += GFX_LINE_ADVANCE;
            continue;
        }
        if (character == '\r')
            continue;
        if (character == '\t') {
            penX += GFX_FONT_ADVANCE * 4;
            continue;
        }

        if (penX >= -32768 && penX <= 32767 &&
            penY >= -32768 && penY <= 32767) {
            gfxChar(surface, (s16)penX, (s16)penY, (char)character, color);
        }
        penX += GFX_FONT_ADVANCE;
    }
}

u8 gfxGlyph5x7Row(char character, u8 row)
{
    u8 code = (u8)character;

    if (row >= GFX_ASCII5X7_HEIGHT)
        return 0;
    if (code < 0x20 || code > 0x7e)
        code = (u8)'?';
    return gfxFont[code - 0x20][gfxFont5x7Rows[row]];
}

void gfxChar5x7(GfxSurface *surface, s16 x, s16 y, char character,
                u16 color)
{
    u8 row;

    if (!gfxSurfaceValid(surface))
        return;
    for (row = 0; row < GFX_ASCII5X7_HEIGHT; ++row) {
        u8 column;
        u8 bits = gfxGlyph5x7Row(character, row);
        s32 targetY = (s32)y + row;

        if (targetY < 0 || targetY >= surface->height)
            continue;
        for (column = 0; column < GFX_ASCII5X7_WIDTH; ++column) {
            s32 targetX = (s32)x + column;
            if (targetX >= 0 && targetX < surface->width &&
                (bits & (1u <<
                    (GFX_ASCII5X7_WIDTH - 1 - column))) != 0) {
                surface->pixels[targetY * surface->stride + targetX] = color;
            }
        }
    }
}

void gfxText5x7(GfxSurface *surface, s16 x, s16 y, const char *text,
                u16 color)
{
    s32 originX = x;
    s32 penX = x;
    s32 penY = y;

    if (!gfxSurfaceValid(surface) || text == NULL)
        return;
    while (*text != '\0') {
        unsigned char character = (unsigned char)*text++;

        if (character == '\n') {
            penX = originX;
            penY += GFX_ASCII5X7_LINE_ADVANCE;
            continue;
        }
        if (character == '\r')
            continue;
        if (character == '\t') {
            penX += GFX_ASCII5X7_ADVANCE * 4;
            continue;
        }
        if (penX >= -32768 && penX <= 32767 &&
            penY >= -32768 && penY <= 32767)
            gfxChar5x7(surface, (s16)penX, (s16)penY,
                       (char)character, color);
        penX += GFX_ASCII5X7_ADVANCE;
    }
}
